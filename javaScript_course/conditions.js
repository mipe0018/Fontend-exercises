// ============================================================
//                         CONDITIONS
//                         BETINGELSER
// ============================================================
//
// Conditions bruges til at få JavaScript til at træffe
// beslutninger ud fra, om noget er TRUE eller FALSE.
//
// En condition stiller typisk et spørgsmål:
//
// Er x større end 10?
// Er navnet "Anna"?
// Er brugeren logget ind?
//
// Hvis betingelsen er TRUE, udføres en bestemt kode.
// Hvis den er FALSE, kan en anden kode udføres.
//
//
//
// ============================================================
//                         IF
// ============================================================
//
// if bruges til at kontrollere, om en betingelse er TRUE.
//
// Eksempel:
//
// if (alder >= 18) {
//     console.log("Du er myndig");
// }
//
// Hvis alder er 18 eller mere, bliver teksten vist.
//
//
//
// ============================================================
//                         ELSE
// ============================================================
//
// else bruges til at fortælle, hvad der skal ske,
// hvis betingelsen i if er FALSE.
//
// Eksempel:
//
// if (alder >= 18) {
//     console.log("Du er myndig");
// } else {
//     console.log("Du er ikke myndig");
// }
//
// Hvis alder er under 18, bliver else-koden kørt.
//
//
//
// ============================================================
//                       ELSE IF
// ============================================================
//
// else if bruges, når man vil kontrollere flere
// forskellige betingelser.
//
// Eksempel:
//
// if (alder >= 18) {
//     console.log("Voksen");
// } else if (alder >= 13) {
//     console.log("Teenager");
// } else {
//     console.log("Barn");
// }
//
// JavaScript kontrollerer betingelserne oppefra og ned.
//
// Den første betingelse, der er TRUE, bliver udført.
//
